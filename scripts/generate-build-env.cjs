#!/usr/bin/env node
/* Writes src/main/build-env.ts with the production API URLs from .env.production.
 *
 * The main process reads its API URL at runtime, so without this we'd ship a
 * binary that defaults to localhost. We don't want to hardcode production URLs
 * in source (they're a deploy concern), so we generate a tiny module from
 * .env.production at build time. The file is gitignored.
 *
 * Run automatically by `npm run dist` via the `predist` hook.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env.production');
const outPath = path.join(root, 'src/main/build-env.ts');

const parseDotenv = (raw) => {
  const out = {};
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    // Strip optional surrounding quotes
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
};

const env = fs.existsSync(envPath)
  ? parseDotenv(fs.readFileSync(envPath, 'utf8'))
  : (console.warn(`[build-env] ${envPath} not found — emitting empty stub (will fall back to localhost).`), {});

// Renderer reads VITE_WORKSIGHT_API; main reads WORKSIGHT_API. The .env file
// holds the renderer var; we mirror it for main so they always match.
const apiBase = env.WORKSIGHT_API || env.VITE_WORKSIGHT_API || '';
const fileServiceBase = env.WORKSIGHT_FILE_SERVICE || env.VITE_WORKSIGHT_FILE_SERVICE || '';

const banner = `// THIS FILE IS GENERATED — do not edit.
// Generated by scripts/generate-build-env.cjs from .env.production.
// Source code reads from this only as a fallback; the user can still override
// via process.env.WORKSIGHT_API at runtime.
`;

const body = `${banner}
export const BUILD_API_BASE = ${JSON.stringify(apiBase)};
export const BUILD_FILE_SERVICE_BASE = ${JSON.stringify(fileServiceBase)};
`;

fs.writeFileSync(outPath, body);
console.log(`[build-env] wrote ${outPath}`);
console.log(`  API_BASE          = ${apiBase || '(empty — will fall back to localhost)'}`);
console.log(`  FILE_SERVICE_BASE = ${fileServiceBase || '(empty — will fall back to localhost)'}`);
